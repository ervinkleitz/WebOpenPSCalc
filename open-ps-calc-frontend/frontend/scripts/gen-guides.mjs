// The two copies on the home page are checked SEPARATELY and against different
// sources. Checking a tag-stripped whole file would be worthless: JSON-LD lives
// inside <script>, so its own text would satisfy a "is it visible?" test and the
// guard would pass while the visible FAQ said something else entirely.
function assertHomeFaqInSync() {
  const home = fs.readFileSync(path.join(__dirname, "..", "index.html"), "utf8");
  const errs = [];
  const norm = (s) => s.replace(/\s+/g, " ").trim();

  // 1. The FAQPage JSON-LD must match SITE_FAQ exactly, question for question.
  const ldBlocks = [...home.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)]
    .map((m) => { try { return JSON.parse(m[1]); } catch { return null; } });
  const ld = ldBlocks.find((b) => b && b["@type"] === "FAQPage");
  if (!ld) {
    errs.push("index.html has no parseable FAQPage JSON-LD block");
  } else {
    const got = ld.mainEntity.map((e) => ({ q: norm(e.name), a: norm(e.acceptedAnswer.text) }));
    if (got.length !== SITE_FAQ.length) errs.push(`FAQPage has ${got.length} entries, SITE_FAQ has ${SITE_FAQ.length}`);
    SITE_FAQ.forEach(({ q, a }, i) => {
      if (!got[i]) return;
      if (got[i].q !== norm(q)) errs.push(`FAQPage Q${i + 1} question differs:\n    schema: ${got[i].q}\n    source: ${norm(q)}`);
      else if (got[i].a !== norm(a)) errs.push(`FAQPage answer differs for "${norm(q)}"`);
    });
  }

  // 2. The VISIBLE block — markup unbacked by on-page content is a violation.
  const vis = home.match(/<div id="seo-faq">([\s\S]*?)<\/div>\s*<\/div>/);
  if (!vis) {
    errs.push('index.html has no <div id="seo-faq"> block for the FAQ to be visible in');
  } else {
    const text = norm(vis[1].replace(/<[^>]+>/g, " "));
    for (const { q, a } of SITE_FAQ) {
      if (!text.includes(norm(q))) errs.push(`visible FAQ is missing the question: ${norm(q)}`);
      else if (!text.includes(norm(a))) errs.push(`visible FAQ answer differs for: ${norm(q)}`);
    }
  }

  if (errs.length) {
    throw new Error(
      "index.html's FAQ has drifted from SITE_FAQ in gen-guides.mjs.\n"
      + "Update all three: SITE_FAQ, the visible #seo-faq block, and the FAQPage JSON-LD.\n  "
      + errs.join("\n  ")
    );
  }
}

const STAT_ORDER = [["str", "STR"], ["agi", "AGI"], ["vit", "VIT"], ["int", "INT"], ["dex", "DEX"], ["luk", "LUK"]];
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// JSON-LD structured data. `\u003c` escapes every "<" so a stray "</script>" in
// any string value can't break out of the <script> block.
const jsonLdScript = (obj) =>
  `<script type="application/ld+json">${JSON.stringify(obj).replace(/</g, "\\u003c")}</script>`;

